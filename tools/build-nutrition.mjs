// Builds js/lib/nutrition-data.js from the USDA National Nutrient Database for
// Standard Reference, Release 28 (public domain), for the foods listed in
// tools/nutrition-foods.mjs.
//
//   node tools/build-nutrition.mjs <directory with ABBREV.txt and FOOD_DES.txt>
//
// SR28's abbreviated file comes, for example, in the npm package
// fda-nutrient-database (data/), or from USDA as sr28abbr.zip. Each listed food is
// printed with USDA's own description, to check the short name against it.
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { FOODS } from './nutrition-foods.mjs';

const dir = process.argv[2];
if (!dir) {
  console.error('usage: node tools/build-nutrition.mjs <SR28 data directory>');
  process.exit(2);
}

// The nutrients kept, in output order: [key, label, unit, ABBREV.txt column, daily value (FDA, adults) or null, group].
export const NUTRIENTS = [
  ['kcal', 'energy', 'kcal', 3, 2000, 'main'],
  ['protein', 'protein', 'g', 4, 50, 'main'],
  ['fat', 'fat', 'g', 5, 78, 'main'],
  ['sat', 'saturated fat', 'g', 44, 20, 'main'],
  ['mono', 'monounsaturated fat', 'g', 45, null, 'main'],
  ['poly', 'polyunsaturated fat', 'g', 46, null, 'main'],
  ['carbs', 'carbohydrate', 'g', 7, 275, 'main'],
  ['sugar', 'sugars', 'g', 9, null, 'main'],
  ['fiber', 'fibre', 'g', 8, 28, 'main'],
  ['cholesterol', 'cholesterol', 'mg', 47, 300, 'main'],
  ['sodium', 'sodium', 'mg', 15, 2300, 'main'],
  ['water', 'water', 'g', 2, null, 'main'],
  ['calcium', 'calcium', 'mg', 10, 1300, 'mineral'],
  ['iron', 'iron', 'mg', 11, 18, 'mineral'],
  ['magnesium', 'magnesium', 'mg', 12, 420, 'mineral'],
  ['phosphorus', 'phosphorus', 'mg', 13, 1250, 'mineral'],
  ['potassium', 'potassium', 'mg', 14, 4700, 'mineral'],
  ['zinc', 'zinc', 'mg', 16, 11, 'mineral'],
  ['copper', 'copper', 'mg', 17, 0.9, 'mineral'],
  ['manganese', 'manganese', 'mg', 18, 2.3, 'mineral'],
  ['selenium', 'selenium', 'µg', 19, 55, 'mineral'],
  ['vitA', 'vitamin A', 'µg', 33, 900, 'vitamin'],
  ['vitC', 'vitamin C', 'mg', 20, 90, 'vitamin'],
  ['vitD', 'vitamin D', 'µg', 41, 20, 'vitamin'],
  ['vitE', 'vitamin E', 'mg', 40, 15, 'vitamin'],
  ['vitK', 'vitamin K', 'µg', 43, 120, 'vitamin'],
  ['thiamin', 'thiamin (B1)', 'mg', 21, 1.2, 'vitamin'],
  ['riboflavin', 'riboflavin (B2)', 'mg', 22, 1.3, 'vitamin'],
  ['niacin', 'niacin (B3)', 'mg', 23, 16, 'vitamin'],
  ['pantothenic', 'pantothenic acid (B5)', 'mg', 24, 5, 'vitamin'],
  ['b6', 'vitamin B6', 'mg', 25, 1.7, 'vitamin'],
  ['folate', 'folate', 'µg', 29, 400, 'vitamin'],
  ['b12', 'vitamin B12', 'µg', 31, 2.4, 'vitamin'],
  ['choline', 'choline', 'mg', 30, 550, 'vitamin'],
];

const parse = (f) => readFileSync(join(dir, f), 'latin1').split(/\r?\n/).filter(Boolean)
  .map((l) => l.split('^').map((x) => x.replace(/^~|~$/g, '')));
const abbrev = new Map(parse('ABBREV.txt').map((r) => [r[0], r]));
const names = new Map(parse('FOOD_DES.txt').map((r) => [r[0], r[2]]));

const rows = [];
const seen = new Set();
let bad = 0;
for (const [group, list] of Object.entries(FOODS)) {
  for (const [ndb, name, state, keys, household = []] of list) {
    const r = abbrev.get(ndb);
    if (!r) { console.error('missing NDB ' + ndb + ' (' + name + ')'); bad++; continue; }
    if (seen.has(ndb)) { console.error('listed twice: ' + ndb); bad++; continue; }
    seen.add(ndb);
    const values = NUTRIENTS.map(([, , , col]) => (r[col] === '' ? null : Number(r[col])));
    // Household sizes first: counting (2 eggs, a banana) uses the first that isn't a measure.
    const portions = [...household, ...[[r[48], r[49]], [r[50], r[51]]].filter(([g, d]) => g && d).map(([g, d]) => [Number(g), d])];
    rows.push([ndb, group, name, state, keys, values, portions, names.get(ndb)]);
    console.log(ndb, String(values[0]).padStart(4), (name + (state ? ' · ' + state : '')).padEnd(46), '| ' + names.get(ndb));
  }
}
if (bad) process.exit(1);

const out = '// Generated by tools/build-nutrition.mjs from the USDA National Nutrient Database\n' +
  '// for Standard Reference, Release 28 (public domain). Edit tools/nutrition-foods.mjs\n' +
  '// and run the script again rather than changing this file.\n' +
  '//\n' +
  '// NUTRIENTS: [key, label, unit, daily value or null, group]; every value is per 100 g.\n' +
  '// FOODS: [NDB number, group, name, state, search words, values (NUTRIENTS order, null = not\n' +
  '// measured), portions [[grams, description]], USDA description].\n\n' +
  'export const SOURCE = ' + JSON.stringify('USDA National Nutrient Database for Standard Reference, Release 28 (2015); in FoodData Central as "SR Legacy"') + ';\n\n' +
  'export const NUTRIENTS = [\n' + NUTRIENTS.map(([k, l, u, , dv, g]) => '  ' + JSON.stringify([k, l, u, dv, g])).join(',\n') + ',\n];\n\n' +
  'export const FOODS = [\n' + rows.map((r) => '  ' + JSON.stringify(r)).join(',\n') + ',\n];\n';
writeFileSync('js/lib/nutrition-data.js', out);
console.log('\n' + rows.length + ' foods, ' + NUTRIENTS.length + ' nutrients -> js/lib/nutrition-data.js (' + Math.round(out.length / 1024) + ' KB)');
