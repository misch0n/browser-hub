// The command reference, generated from the command definitions so it can't
// drift: docs/commands.md, and the table of areas in README.md (between the
// `commands:start` / `commands:end` markers). A unit test fails when either
// is out of date.
//
//   node tools/docs-commands.mjs           check (exit 1 when out of date)
//   node tools/docs-commands.mjs --write   regenerate both

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { createCommands } from '../js/commands/index.js';

const root = fileURLToPath(new URL('..', import.meta.url));
const COMMANDS_MD = root + 'docs/commands.md';
const README = root + 'README.md';
const START = '<!-- commands:start (generated by tools/docs-commands.mjs; edit the command definitions, not this table) -->';
const END = '<!-- commands:end -->';

function groups() {
  const { defs } = createCommands(() => ({}));
  const out = new Map(); // in registration order, as `help` shows them
  for (const d of defs.filter((x) => !x.hidden)) out.set(d.group, [...(out.get(d.group) || []), d]);
  return out;
}

const flagsOf = (d) => [d.private && 'private', d.noHistory && 'no ↑ history', d.ephemeral && 'for now', d.noUndo && 'no undo'].filter(Boolean);

export function commandsMarkdown() {
  const lines = [
    '# Commands',
    '',
    'Every built-in command, by the group `help` shows it in. Generated from the',
    'definitions in `js/commands/` by `node tools/docs-commands.mjs --write`; a unit',
    'test fails when this file is out of date, so don\'t edit it by hand.',
    '',
    'Flags: **private** stays out of the shared (synced) history; **no ↑ history**',
    'isn\'t kept for ↑ recall either; **for now** is shown, then removed when the next',
    'command runs; **no undo** is never an undo step.',
    '',
  ];
  for (const [group, defs] of groups()) {
    lines.push('## ' + group, '');
    for (const d of defs) {
      const flags = flagsOf(d);
      lines.push('### `' + d.name + '`', '', d.desc + (flags.length ? ' *(' + flags.join(', ') + ')*' : ''), '');
      lines.push('```', ...d.usage, '```', '');
      if (d.examples && d.examples.length) lines.push('Examples: ' + d.examples.map((x) => '`' + x.replace(/`/g, "'") + '`').join(' · '), '');
    }
  }
  return lines.join('\n').replace(/\n+$/, '\n');
}

export function readmeTable() {
  const rows = ['| Area | Commands |', '| --- | --- |'];
  for (const [group, defs] of groups()) rows.push('| ' + group + ' | ' + defs.map((d) => '`' + d.name + '`').join(', ') + ' |');
  return [START, ...rows, END].join('\n');
}

export function readmeWithTable(readme) {
  const a = readme.indexOf('<!-- commands:start'), b = readme.indexOf(END);
  if (a < 0 || b < a) throw new Error('README.md has no commands:start / commands:end markers');
  return readme.slice(0, a) + readmeTable() + readme.slice(b + END.length);
}

// -> [] when both are current, else the names of the stale files.
export function staleDocs() {
  const stale = [];
  if (readFileSync(COMMANDS_MD, 'utf8') !== commandsMarkdown()) stale.push('docs/commands.md');
  const readme = readFileSync(README, 'utf8');
  if (readmeWithTable(readme) !== readme) stale.push('README.md (command table)');
  return stale;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  if (process.argv.includes('--write')) {
    writeFileSync(COMMANDS_MD, commandsMarkdown());
    writeFileSync(README, readmeWithTable(readFileSync(README, 'utf8')));
    console.log('wrote docs/commands.md and the README command table');
  } else {
    const stale = staleDocs();
    if (stale.length) {
      console.error('out of date: ' + stale.join(', ') + '\nrun: node tools/docs-commands.mjs --write');
      process.exit(1);
    }
    console.log('command docs are current');
  }
}
